#include "planosz/errors.h"

static const char *const names[PLANOSZ_CODE_COUNT] = {
	[PLANOSZ_OK] = "OK",
	[PLANOSZ_REJECT_UNKNOWN_SKILL] = "REJECT_UNKNOWN_SKILL",
	[PLANOSZ_REJECT_BAD_ARGS] = "REJECT_BAD_ARGS",
	[PLANOSZ_REJECT_PERMISSION] = "REJECT_PERMISSION",
	[PLANOSZ_REJECT_RESOURCE_CONFLICT] = "REJECT_RESOURCE_CONFLICT",
	[PLANOSZ_REJECT_DEADLINE_INFEASIBLE] = "REJECT_DEADLINE_INFEASIBLE",
	[PLANOSZ_REJECT_UNSUPPORTED_IR] = "REJECT_UNSUPPORTED_IR",
	[PLANOSZ_REJECT_SAFETY_CLASS] = "REJECT_SAFETY_CLASS",
	[PLANOSZ_REJECT_BAD_PLAN] = "REJECT_BAD_PLAN",
	[PLANOSZ_EXEC_TIMEOUT] = "EXEC_TIMEOUT",
	[PLANOSZ_EXEC_SKILL_FAIL] = "EXEC_SKILL_FAIL",
	[PLANOSZ_EXEC_CANCELLED] = "EXEC_CANCELLED",
	[PLANOSZ_EXEC_BACKEND_UNAVAILABLE] = "EXEC_BACKEND_UNAVAILABLE",
};

const char *planosz_code_str(enum planosz_code code)
{
	if ((unsigned int)code >= PLANOSZ_CODE_COUNT || names[code] == 0) {
		return "UNKNOWN_CODE";
	}
	return names[code];
}
