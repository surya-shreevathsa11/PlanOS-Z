"""IDL -> C: registry table, per-skill WCET functions and resource-claim templates
(runtime/src/registry/skill_table.gen.*).

The device never trusts WCET / resource numbers carried by an uploaded plan; it evaluates the
functions generated here. WCET expressions are the same restricted subset the host evaluates
(see expr.py), translated to int64 C arithmetic with Python's floor-division semantics.
"""

from __future__ import annotations

import ast
import string

from .compile import SAFETY_CODES, arg_range
from .idl import Contract, Registry

POWER_CODES = {"ACTIVE_HIGH": 0, "ACTIVE_LOW": 1, "SLEEP": 2}
BANNER = "/* Generated by `planoszc codegen` from the IDL YAML files - DO NOT EDIT. */\n"
MAX_CLAIMS = 4
MAX_CLAIM_VARIANTS = 8
MAX_RESOURCES = 32
INT_TYPES = {"uint8", "uint16", "uint32", "int8", "int16", "int32", "bool", "enum"}


class CodegenError(Exception):
    pass


def _sym(skill_id: str) -> str:
    return skill_id.upper().replace(".", "_")


def _fn(skill_id: str) -> str:
    return "wcet_" + skill_id.replace(".", "_")


# ----------------------------------------------------------------------------- WCET -> C
_BIN_C = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*"}
_CMP_C = {ast.Eq: "==", ast.NotEq: "!=", ast.Lt: "<", ast.LtE: "<=", ast.Gt: ">", ast.GtE: ">="}


class _ToC:
    def __init__(self, contract: Contract):
        self.c = contract
        self.names = list(contract.args)

    def err(self, msg: str) -> CodegenError:
        return CodegenError(f"{self.c.skill_id}: wcet_ms '{self.c.wcet_src}': {msg}")

    def name(self, node: ast.Name) -> str:
        spec = self.c.args[node.id]
        if spec["type"] not in INT_TYPES:
            raise self.err(f"arg '{node.id}' has type {spec['type']}; only integer/enum/bool args may appear")
        return f"(int64_t)a[{self.names.index(node.id)}]"

    def operand(self, node: ast.AST, peer: ast.AST | None) -> str:
        """A comparison operand; a string constant is only legal opposite an enum arg."""
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            if isinstance(peer, ast.Name) and self.c.args[peer.id]["type"] == "enum":
                values = self.c.args[peer.id]["values"]
                if node.value not in values:
                    raise self.err(f"'{node.value}' is not a value of enum arg '{peer.id}'")
                return str(values.index(node.value))
            raise self.err("string constants may only be compared with an enum arg")
        return self.expr(node)

    def expr(self, node: ast.AST) -> str:
        if isinstance(node, ast.Constant):
            v = node.value
            if isinstance(v, float):
                if not v.is_integer():
                    raise self.err(f"non-integer constant {v}")
                v = int(v)
            if isinstance(v, int):
                return f"INT64_C({v})"
            raise self.err("bare string constant")
        if isinstance(node, ast.Name):
            return f"({self.name(node)})"
        if isinstance(node, ast.BinOp):
            lhs, rhs = self.expr(node.left), self.expr(node.right)
            op = type(node.op)
            if op in _BIN_C:
                return f"({lhs} {_BIN_C[op]} {rhs})"
            if op is ast.FloorDiv:
                return f"pz_fdiv({lhs}, {rhs})"
            if op is ast.Mod:
                return f"pz_fmod({lhs}, {rhs})"
            raise self.err("'/' is not supported in device WCET models; use '//' (integer arithmetic only)")
        if isinstance(node, ast.UnaryOp):
            return f"(-{self.expr(node.operand)})"
        if isinstance(node, ast.Compare):
            parts = []
            left = node.left
            for op, right in zip(node.ops, node.comparators):
                parts.append(f"({self.operand(left, right)} {_CMP_C[type(op)]} {self.operand(right, left)})")
                left = right
            return "(" + " && ".join(parts) + ")"
        if isinstance(node, ast.IfExp):
            return f"({self.expr(node.test)} ? {self.expr(node.body)} : {self.expr(node.orelse)})"
        if isinstance(node, ast.Call):
            fn = "pz_min" if node.func.id == "min" else "pz_max"  # type: ignore[union-attr]
            args = [self.expr(a) for a in node.args]
            out = args[0]
            for a in args[1:]:
                out = f"{fn}({out}, {a})"
            return out
        raise self.err(f"cannot translate {type(node).__name__}")  # pragma: no cover


def wcet_to_c(contract: Contract) -> str:
    """C expression (int64) equal to contract.wcet_ms(args) for integer-valued models."""
    return _ToC(contract).expr(contract._wcet.body)


# ----------------------------------------------------------------------------- resources
def _placeholders(template: str) -> list[str]:
    return [f for _, f, _, _ in string.Formatter().parse(template) if f]


def expand_claim(contract: Contract, template: str) -> tuple[int, list[str]]:
    """(arg index or -1, list of concrete resource names, one per enum variant)."""
    fields = _placeholders(template)
    if not fields:
        return -1, [template]
    if len(set(fields)) > 1:
        raise CodegenError(f"{contract.skill_id}: resource '{template}' references several args (unsupported)")
    name = fields[0]
    spec = contract.args.get(name)
    if spec is None or spec["type"] != "enum":
        raise CodegenError(f"{contract.skill_id}: resource '{template}': arg '{name}' must be an enum")
    values = spec["values"]
    if len(values) > MAX_CLAIM_VARIANTS:
        raise CodegenError(f"{contract.skill_id}: resource '{template}' expands to >{MAX_CLAIM_VARIANTS} names")
    return list(contract.args).index(name), [template.format(**{name: v}) for v in values]


def resource_universe(reg: Registry) -> list[str]:
    """Sorted global resource name table = the device's resource bit space."""
    names: set[str] = set()
    for c in reg.all():
        for r in c.resources:
            names.update(expand_claim(c, r.template)[1])
    out = sorted(names)
    if len(out) > MAX_RESOURCES:
        raise CodegenError(f"{len(out)} distinct resources exceed the 32-bit mask space")
    return out


def device_masks(reg: Registry, contract: Contract, resolved: dict) -> tuple[int, int, int]:
    """Reference model of planosz_registry_derive() for tests: (wcet_ms, excl_mask, shared_mask)."""
    import math

    universe = resource_universe(reg)
    excl = shared = 0
    for name, mode in contract.claims(resolved):
        bit = 1 << universe.index(name)
        if mode == "exclusive":
            excl |= bit
        else:
            shared |= bit
    return math.ceil(contract.wcet_ms(resolved)), excl, shared


# ----------------------------------------------------------------------------- emit
def gen_header(reg: Registry) -> str:
    universe = resource_universe(reg)
    o = [BANNER, "#ifndef PLANOSZ_SKILL_TABLE_GEN_H_", "#define PLANOSZ_SKILL_TABLE_GEN_H_", "",
         '#include "planosz/registry.h"', "", "/* Skill indices (sorted by skill_id; used by the IR) */", "enum planosz_skill_idx {"]
    for c in reg.all():
        o.append(f"\tPLANOSZ_SKILL_{_sym(c.skill_id)} = {c.index},")
    o += [f"\tPLANOSZ_SKILL_COUNT = {len(reg.all())}", "};", "", "/* Permission bits */"]
    for i, p in enumerate(reg.permissions()):
        o.append(f"#define PLANOSZ_PERM_{p} (1u << {i})")
    o += ["", "/* Device resource space: bit i of an excl/shared mask is planosz_res_names[i] */",
          f"#define PLANOSZ_RES_COUNT {len(universe)}",
          "extern const char *const planosz_res_names[PLANOSZ_RES_COUNT];", "",
          "extern const struct planosz_skill_contract planosz_skill_table[PLANOSZ_SKILL_COUNT];", "",
          "#endif /* PLANOSZ_SKILL_TABLE_GEN_H_ */", ""]
    return "\n".join(o)


def _claim_c(reg_universe: list[str], contract: Contract, claim) -> str:
    arg, names = expand_claim(contract, claim.template)
    idx = ", ".join(str(reg_universe.index(n)) for n in names)
    mode = "PLANOSZ_CLAIM_EXCLUSIVE" if claim.mode == "exclusive" else "PLANOSZ_CLAIM_SHARED"
    return f"{{ {mode}, {arg}, {len(names)}, {{ {idx} }} }}"


def gen_source(reg: Registry) -> str:
    universe = resource_universe(reg)
    o = [BANNER, '#include "planosz/skill_table.gen.h"', '#include "planosz/wcet_util.h"', "",
         "const char *const planosz_res_names[PLANOSZ_RES_COUNT] = {"]
    o += [f'\t"{n}",' for n in universe]
    o += ["};", "", "/* Per-skill WCET (ms), generated from the IDL `wcet_ms` expressions. args[] are the",
          " * resolved IR args (enum = index). */"]
    for c in reg.all():
        if len(c.resources) > MAX_CLAIMS:
            raise CodegenError(f"{c.skill_id}: more than {MAX_CLAIMS} resource claims")
        body = wcet_to_c(c)
        o.append(f"static uint32_t {_fn(c.skill_id)}(const int32_t *a)")
        o.append("{")
        if "a[" not in body:
            o.append("\t(void)a;")
        o.append(f"\treturn pz_u32({body});")
        o.append("}")
        o.append("")
    o.append("const struct planosz_skill_contract planosz_skill_table[PLANOSZ_SKILL_COUNT] = {")
    for c in reg.all():
        pm = " | ".join(f"PLANOSZ_PERM_{p}" for p in c.permissions) or "0"
        args = []
        for name, spec in c.args.items():
            lo, hi = arg_range(spec)
            args.append(f'{{ "{name}", {lo}, {hi} }}')
        claims = [_claim_c(universe, c, r) for r in c.resources]
        o.append("\t{")
        o.append(f'\t\t.skill_id = "{c.skill_id}", .version = {c.version},')
        o.append(f"\t\t.perm_mask = {pm},")
        o.append(f"\t\t.safety_class = {SAFETY_CODES[c.safety_class]}, /* {c.safety_class} */")
        o.append(f"\t\t.power_class = {POWER_CODES[c.power_class]}, /* {c.power_class} */")
        o.append(f"\t\t.n_args = {len(c.args)},")
        o.append(f"\t\t.args = {{ {', '.join(args) if args else '{ 0 }'} }},")
        o.append(f"\t\t.n_claims = {len(claims)},")
        o.append(f"\t\t.claims = {{ {', '.join(claims) if claims else '{ 0 }'} }},")
        o.append(f"\t\t.wcet_fn = {_fn(c.skill_id)},")
        o.append(f'\t\t.wcet_model = "{c.wcet_src}",')
        o.append("\t},")
    o += ["};", ""]
    return "\n".join(o)
