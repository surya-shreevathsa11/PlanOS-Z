"""Plan -> compact IR (v1). Steps are emitted in topological order with bit-masks so the
on-device admission/executor can work without YAML, strings or floats."""

from __future__ import annotations

from typing import Any

from .admission import Admission
from .idl import Registry

IR_VERSION = 1
OP_CODES = {">": 0, ">=": 1, "<": 2, "<=": 3, "==": 4, "!=": 5}
MAX_STEPS = 32
MAX_ARGS = 4
SAFETY_CODES = {"SAFE": 0, "REQUIRES_CONFIRM": 1, "HAZARDOUS": 2}


class CompileError(Exception):
    pass


def encode_arg(spec: dict, value: Any) -> int:
    if spec["type"] == "enum":
        return spec["values"].index(value)
    if spec["type"] == "bool":
        return int(value)
    if spec["type"] == "float":
        return int(round(value * 1000))
    return int(value)


def arg_range(spec: dict) -> tuple[int, int]:
    from .idl import INT_BOUNDS

    t = spec["type"]
    if t == "enum":
        return 0, len(spec["values"]) - 1
    if t == "bool":
        return 0, 1
    if t == "float":
        return int(spec.get("min", -2e6) * 1000), int(spec.get("max", 2e6) * 1000)
    if t == "string":
        return 0, 0
    lo, hi = INT_BOUNDS[t]
    return max(lo, int(spec.get("min", lo))), min(hi, int(spec.get("max", hi)))


def compile_plan(adm: Admission, registry: Registry) -> dict:
    if not adm.steps:
        raise CompileError("cannot compile a plan that failed structural/contract checks")
    perms = registry.permissions()
    res_names = sorted({r for s in adm.steps for r, _ in s.claims})
    if len(adm.steps) > MAX_STEPS or len(res_names) > 32:
        raise CompileError("plan exceeds IR limits (32 steps / 32 resources)")
    pos = {sid: i for i, sid in enumerate(adm.order)}
    steps = []
    for sid in adm.order:
        st = adm.step(sid)
        excl = shared = 0
        for name, mode in st.claims:
            bit = 1 << res_names.index(name)
            if mode == "exclusive":
                excl |= bit
            else:
                shared |= bit
        arg_names = list(st.contract.args)
        if len(arg_names) > MAX_ARGS:
            raise CompileError(f"{st.action}: more than {MAX_ARGS} args")
        entry = {
            "id": sid,
            "skill": st.contract.index,
            "action": st.action,
            "wcet_ms": st.wcet_ms,
            "deps_mask": sum(1 << pos[n] for n in st.needs),
            "excl_mask": excl,
            "shared_mask": shared,
            "mutex_mask": sum(1 << pos[o] for o in adm.mutex.get(sid, ())),
            "confirm": st.confirm,
            "args": [encode_arg(st.contract.args[a], st.args[a]) for a in arg_names],
            "when_step": -1,
            "when_op": 0,
            "when_value_milli": 0,
        }
        if st.when:
            ref_step, _field = st.when["ref"].split(".")
            entry["when_step"] = pos[ref_step]
            entry["when_op"] = OP_CODES[st.when["op"]]
            v = st.when["value"]
            entry["when_value_milli"] = int(round(float(v) * 1000)) if not isinstance(v, str) else 0
        steps.append(entry)
    return {
        "ir_version": IR_VERSION,
        "plan_id": adm.plan_id,
        "deadline_ms": adm.deadline_ms,
        "perm_mask": sum(1 << perms.index(p) for p in adm.permissions if p in perms),
        "resources": res_names,
        "steps": steps,
    }


def ir_to_c_header(ir: dict, symbol: str = "PLAN") -> str:
    out = [
        "/* Generated by `planoszc compile --emit c` - do not edit. */",
        '#include "planosz/ir.h"',
        "",
        f"static const struct planosz_ir_step {symbol}_STEPS[] = {{",
    ]
    for s in ir["steps"]:
        args = ", ".join(str(a) for a in s["args"]) or "0"
        out.append(
            f'\t{{ .id = "{s["id"]}", .skill_idx = {s["skill"]}, .wcet_ms = {s["wcet_ms"]}u, '
            f'.deps_mask = 0x{s["deps_mask"]:x}u, .excl_mask = 0x{s["excl_mask"]:x}u, '
            f'.shared_mask = 0x{s["shared_mask"]:x}u, .mutex_mask = 0x{s["mutex_mask"]:x}u, '
            f'.confirm = {int(s["confirm"])}, .args = {{ {args} }}, '
            f'.when_step = {s["when_step"]}, .when_op = {s["when_op"]}, '
            f'.when_value_milli = {s["when_value_milli"]} }},'
        )
    out += [
        "};",
        "",
        f"static const struct planosz_ir_plan {symbol} = {{",
        f'\t.plan_id = "{ir["plan_id"]}",',
        f'\t.deadline_ms = {ir["deadline_ms"]}u,',
        f'\t.perm_mask = 0x{ir["perm_mask"]:x}u,',
        f'\t.n_steps = {len(ir["steps"])},',
        f"\t.steps = {symbol}_STEPS,",
        "};",
        "",
    ]
    return "\n".join(out)
